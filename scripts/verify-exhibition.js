import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import vm from 'node:vm';
import {chromium} from '@playwright/test';
const base=process.env.TEST_ORIGIN||'http://127.0.0.1:8000';
const source=await fs.readFile('play-rules.js','utf8'),sandbox={window:{},URLSearchParams,location:{hostname:'semantic-map-mvp.vercel.app',search:'?test=welcome'}};
vm.runInNewContext(source,sandbox);
const rules=sandbox.window.SemanticMap.playRules;
assert.equal(rules.walkingOnly,true,'Public query strings cannot restore indoor mode');
const campus={lat:34.81036,lng:135.56108,accuracy:350,at:Date.now()};
const station={lat:34.81525,lng:135.5622};
assert.ok(rules.campusArrival(campus,station),'Indoor OIC GPS can unlock the nearby station from campus');
assert.ok(!rules.campusArrival({...campus,lat:34.83},station),'Campus exception does not extend across the city');
assert.ok(!rules.campusArrival({...campus,accuracy:900},station));
assert.ok(!rules.campusArrival({...campus,at:Date.now()-121000},station));
assert.ok(!rules.campusArrival(campus,{lat:35,lng:135}),'Distant tasks stay locked');
const browser=await chromium.launch(),errors=[];
const gameKey='kotoba-hunter-progress-v1',weekKey='kotoba-hunter-seven-days-v1',freeKey='kotoba-hunter-free-map-v1';
await fs.mkdir('work/exhibition-mode',{recursive:true});
try{
    const context=await browser.newContext({viewport:{width:390,height:844},permissions:['geolocation'],geolocation:{latitude:campus.lat,longitude:campus.lng,accuracy:350},reducedMotion:'reduce'});
    const page=await context.newPage();page.on('pageerror',e=>errors.push(e.message));
    await page.goto(base+'/?test=before-play');
    const start=page.locator('[data-action="begin-play"]');await start.waitFor();
    assert.equal(await page.locator('[name="play-mode"]').count(),0);
    assert.ok(await start.isDisabled());
    await page.locator('#courier-dialog-body').evaluate(el=>el.scrollTop=el.scrollHeight);
    await start.click();await page.locator('[data-opening-beat="welcome"]').waitFor();
    await page.screenshot({path:'work/exhibition-mode/welcome.png'});
    await page.goto(base+'/?test=ending');
    const letter=await page.evaluate(()=>SemanticMap.letterTutorial.snapshot());
    await page.evaluate(({letter,gameKey,weekKey,freeKey})=>{
        const date=new Date(),stamp=[date.getFullYear(),String(date.getMonth()+1).padStart(2,'0'),String(date.getDate()).padStart(2,'0')].join('-');
        localStorage.setItem(gameKey,JSON.stringify({version:1,language:'ja',letter,progress:{index:3,cards:[{step:0,object:'letter',word:'手紙',kana:'てがみ',photo:''},{step:1,object:'drink',word:'お茶',kana:'おちゃ',photo:''},{step:2,object:'tree',word:'木',kana:'き',photo:''},{step:3,object:'station',word:'駅',kana:'えき',photo:''}],done:true,receipt:false,mode:'preview',phase:'encounter'}}));
        localStorage.setItem(weekKey,JSON.stringify({version:1,completed:{1:{date:stamp}},entries:{},active:true,scene:'explore',day:2,sideLog:[]}));
        localStorage.setItem('kotoba-hunter-before-play-v2','seen');
        localStorage.removeItem(freeKey);
    },{letter,gameKey,weekKey,freeKey});
    await page.goto(base);await page.locator('.free-board').waitFor();
    assert.equal(await page.locator('[data-free="mode"]').count(),0);
    assert.equal(await page.evaluate(k=>JSON.parse(localStorage.getItem(k)).progress.mode,gameKey),'field','Old main progress migrates without resetting the journey');
    await page.locator('[data-free="locate"]').click();
    await page.waitForFunction(()=>document.querySelectorAll('.free-map-marker').length>0);
    const board=await page.evaluate(k=>JSON.parse(localStorage.getItem(k)),freeKey);
    assert.ok(board.missions.every(m=>rules.campusArrival({...campus,at:Date.now()},m.spot)),'All generated OIC nearby missions can start from campus');
    const target=board.missions.find(m=>m.spot.kind==='station');assert.ok(target);
    await page.locator('[data-free="list"]').first().click();
    await page.locator('[data-free="select"][data-id="'+target.id+'"]').click();
    await page.waitForFunction(()=>!document.querySelector('[data-free="start"]').disabled);
    await page.screenshot({path:'work/exhibition-mode/oic-task-ready.png'});
    await context.setGeolocation({latitude:campus.lat+.01,longitude:campus.lng,accuracy:20});
    await page.waitForFunction(()=>document.querySelector('[data-free="start"]').disabled);
    await context.setGeolocation({latitude:campus.lat,longitude:campus.lng,accuracy:350});
    await page.waitForFunction(()=>!document.querySelector('[data-free="start"]').disabled);
    await page.locator('[data-free="start"]').click();await page.locator('[data-free="sample"]').waitFor();
    await page.locator('[data-free="sample"]').click();await page.locator('[data-free="use-sample"]').click();
    await page.locator('[data-free="complete"]').click();await page.locator('.free-board').waitFor();
    assert.equal(await page.evaluate(k=>JSON.parse(localStorage.getItem(k)).history.length,freeKey),1);
    await page.reload();await page.locator('.free-board').waitFor();
    assert.equal(await page.locator('[data-free="mode"]').count(),0);
    assert.equal(await page.evaluate(k=>JSON.parse(localStorage.getItem(k)).history.length,freeKey),1);
    await page.evaluate(k=>{const s=JSON.parse(localStorage.getItem(k));s.mode='indoor';localStorage.setItem(k,JSON.stringify(s));},freeKey);
    await page.reload();await page.locator('.free-board').waitFor();
    assert.equal(await page.evaluate(k=>JSON.parse(localStorage.getItem(k)).mode,freeKey),'walk');
    assert.equal(await page.evaluate(k=>JSON.parse(localStorage.getItem(k)).history.length,freeKey),1,'Indoor save migration keeps completed missions');
    assert.deepEqual(errors,[]);await context.close();
    console.log('PASS: walking-only onboarding, scroll gate, old progress migration, OIC indoor GPS arrival, outside-campus lock, photo sample completion and saved history. No real Gemini requests.');
}finally{await browser.close();}
